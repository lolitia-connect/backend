func TestResetSequencesOnlyTouchesCopiedPlans(t *testing.T) {
	dsn := os.Getenv("PPANEL_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set PPANEL_TEST_POSTGRES_DSN to run PostgreSQL sequence test")
	}
	database, err := sql.Open("postgres", dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer database.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	if err := database.PingContext(ctx); err != nil {
		t.Fatal(err)
	}
	suffix := strconv.FormatInt(time.Now().UnixNano(), 10)
	copiedTable := "sequence_scope_copy_" + suffix
	skippedTable := "sequence_scope_skip_" + suffix
	for _, table := range []string{copiedTable, skippedTable} {
		if _, err := database.ExecContext(ctx, `CREATE TABLE `+quotePGIdent(table)+` (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`); err != nil {
			t.Fatal(err)
		}
	}
	defer func() {
		if _, err := database.ExecContext(context.Background(), `DROP TABLE IF EXISTS `+quotePGIdent(copiedTable)+`, `+quotePGIdent(skippedTable)); err != nil {
			t.Error(err)
		}
	}()
	if _, err := database.ExecContext(ctx, `INSERT INTO `+quotePGIdent(copiedTable)+` (id) VALUES (42)`); err != nil {
		t.Fatal(err)
	}
	if _, err := database.ExecContext(ctx, `INSERT INTO `+quotePGIdent(skippedTable)+` DEFAULT VALUES`); err != nil {
		t.Fatal(err)
	}
	if _, err := database.ExecContext(ctx, `SELECT setval(pg_get_serial_sequence($1, 'id'), 100, true)`, `public.`+skippedTable); err != nil {
		t.Fatal(err)
	}
	plans := []tablePlan{{Name: copiedTable, Columns: []postgresColumn{{Name: "id", Identity: true}}}}
	if err := resetSequences(ctx, database, "public", plans); err != nil {
		t.Fatal(err)
	}
	var copiedNext, skippedNext int64
	if err := database.QueryRowContext(ctx, `SELECT nextval(pg_get_serial_sequence($1, 'id'))`, `public.`+copiedTable).Scan(&copiedNext); err != nil {
		t.Fatal(err)
	}
	if err := database.QueryRowContext(ctx, `SELECT nextval(pg_get_serial_sequence($1, 'id'))`, `public.`+skippedTable).Scan(&skippedNext); err != nil {
		t.Fatal(err)
	}
	if copiedNext != 43 || skippedNext != 101 {
		t.Fatalf("sequence values = copied %d, skipped %d; want 43 and 101", copiedNext, skippedNext)
	}
}

func TestBuildPlansSkipsGeneratedColumns(t *testing.T) {
	cols := []postgresColumn{
		{Name: "id", DataType: "bigint"},
		{Name: "computed", DataType: "text", Generated: true},
		{Name: "missing", DataType: "text"},
		{Name: "name", DataType: "text"},
	}
	source := map[string]struct{}{
		"id":       {},
		"computed": {},
		"name":     {},
	}
	common := make([]postgresColumn, 0, len(cols))
	for _, col := range cols {
		if col.Generated {
			continue
		}
		if _, ok := source[col.Name]; ok {
			common = append(common, col)
		}
	}
	if len(common) != 2 || common[0].Name != "id" || common[1].Name != "name" {
		t.Fatalf("common columns = %#v", common)
	}
}

