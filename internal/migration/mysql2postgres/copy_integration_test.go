package mysql2postgres

import (
	"context"
	"database/sql"
	"fmt"
	"os"
	"strings"
	"testing"
	"time"
)

func TestMigrateCopiesSelectedTablesAndPreservesData(t *testing.T) {
	mysqlDSN, postgresDSN := os.Getenv("PPANEL_TEST_MYSQL_DSN"), os.Getenv("PPANEL_TEST_POSTGRES_DSN")
	if mysqlDSN == "" || postgresDSN == "" {
		t.Skip("set PPANEL_TEST_MYSQL_DSN and PPANEL_TEST_POSTGRES_DSN to run the copy integration test")
	}
	ctx, cancel := context.WithTimeout(t.Context(), time.Minute)
	defer cancel()
	open := func(driver, dsn string) *sql.DB {
		t.Helper()
		db, err := sql.Open(driver, dsn)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = db.Close() })
		return db
	}
	source, target := open("mysql", mysqlDSN), open("postgres", postgresDSN)
	exec := func(db *sql.DB, statement string) {
		t.Helper()
		if _, err := db.ExecContext(ctx, statement); err != nil {
			t.Fatal(err)
		}
	}
	suffix := fmt.Sprint(time.Now().UnixNano())
	schema, parent, child, broken := "migration_"+suffix, "z_parent_"+suffix, "a_child_"+suffix, "bad_"+suffix
	parentSrc, childSrc, brokenSrc := quoteMySQLIdent(parent), quoteMySQLIdent(child), quoteMySQLIdent(broken)
	schemaSQL := quotePGIdent(schema)
	parentDst, childDst, brokenDst := schemaSQL+"."+quotePGIdent(parent), schemaSQL+"."+quotePGIdent(child), schemaSQL+"."+quotePGIdent(broken)
	for _, item := range []struct {
		db    *sql.DB
		query string
	}{
		{source, "DROP TABLE IF EXISTS " + strings.Join([]string{parentSrc, childSrc, brokenSrc}, ", ")},
		{target, "DROP SCHEMA IF EXISTS " + schemaSQL + " CASCADE"},
	} {
		t.Cleanup(func() {
			cleanup, stop := context.WithTimeout(context.Background(), 10*time.Second)
			defer stop()
			if _, err := item.db.ExecContext(cleanup, item.query); err != nil {
				t.Error(err)
			}
		})
	}
	exec(source, "CREATE TABLE "+parentSrc+" (id BIGINT PRIMARY KEY, enabled TINYINT, seen DATETIME NULL)")
	exec(source, "INSERT INTO "+parentSrc+" VALUES (43,1,'2026-05-21 14:30:00'), (90,0,NULL)")
	exec(source, "CREATE TABLE "+childSrc+" (id BIGINT PRIMARY KEY, parent_id BIGINT NOT NULL, name VARCHAR(50) NOT NULL)")
	exec(source, "INSERT INTO "+childSrc+" VALUES (7,43,'copied')")
	exec(target, "CREATE SCHEMA "+schemaSQL)
	exec(target, "CREATE TABLE "+parentDst+" (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, enabled BOOLEAN, seen TIMESTAMPTZ)")
	exec(target, "CREATE TABLE "+childDst+" (id BIGINT PRIMARY KEY, parent_id BIGINT NOT NULL REFERENCES "+parentDst+", name TEXT, normalized TEXT GENERATED ALWAYS AS (UPPER(name)) STORED)")
	exec(target, "INSERT INTO "+parentDst+" (id, enabled) VALUES (7, TRUE)")

	args := []string{"--mysql", mysqlDSN, "--postgres", postgresDSN, "--schema", schema, "--tables", parent + "," + child, "--location", "Asia/Shanghai", "--batch-size", "1", "--truncate"}
	if err := Run(ctx, args); err == nil || !strings.Contains(err.Error(), "--yes") {
		t.Fatal("an unconfirmed truncate did not require operator confirmation")
	}
	if err := Run(ctx, append(args, "--dry-run")); err != nil {
		t.Fatal(err)
	}
	var id int64
	if err := target.QueryRowContext(ctx, "SELECT id FROM "+parentDst).Scan(&id); err != nil || id != 7 {
		t.Fatalf("dry run changed target rows: id=%d, err=%v", id, err)
	}
	if err := Run(ctx, append(args, "--yes")); err != nil {
		t.Fatal(err)
	}
	var count int
	if err := target.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+parentDst).Scan(&count); err != nil || count != 2 {
		t.Fatalf("copied parent count=%d, err=%v", count, err)
	}
	var enabled bool
	var seen sql.NullTime
	if err := target.QueryRowContext(ctx, "SELECT enabled, seen FROM "+parentDst+" WHERE id=43").Scan(&enabled, &seen); err != nil || !enabled || !seen.Valid || !seen.Time.Equal(time.Date(2026, 5, 21, 6, 30, 0, 0, time.UTC)) {
		t.Fatalf("copied parent 43 enabled=%t seen=%v err=%v", enabled, seen, err)
	}
	if err := target.QueryRowContext(ctx, "SELECT enabled, seen FROM "+parentDst+" WHERE id=90").Scan(&enabled, &seen); err != nil || enabled || seen.Valid {
		t.Fatalf("copied parent 90 enabled=%t seen=%v err=%v", enabled, seen, err)
	}
	var parentID int64
	var normalized string
	if err := target.QueryRowContext(ctx, "SELECT parent_id, normalized FROM "+childDst+" WHERE id=7").Scan(&parentID, &normalized); err != nil || parentID != 43 || normalized != "COPIED" {
		t.Fatalf("copied child parent=%d name=%q err=%v", parentID, normalized, err)
	}
	if err := target.QueryRowContext(ctx, "INSERT INTO "+parentDst+" (enabled) VALUES (TRUE) RETURNING id").Scan(&id); err != nil || id != 91 {
		t.Fatalf("next identity=%d err=%v, want 91", id, err)
	}

	exec(source, "CREATE TABLE "+brokenSrc+" (id BIGINT PRIMARY KEY, enabled VARCHAR(16))")
	exec(source, "INSERT INTO "+brokenSrc+" VALUES (1,'true'), (2,'unknown')")
	exec(target, "CREATE TABLE "+brokenDst+" (id BIGINT PRIMARY KEY, enabled BOOLEAN)")
	exec(target, "INSERT INTO "+brokenDst+" VALUES (3, FALSE)")
	copyFlags := []string{"--mysql", mysqlDSN, "--postgres", postgresDSN, "--schema", schema, "--tables", broken}
	if err := Run(ctx, copyFlags); err == nil || !strings.Contains(err.Error(), broken+".enabled") {
		t.Fatalf("copy of invalid boolean returned %v", err)
	}
	if err := target.QueryRowContext(ctx, "SELECT COUNT(*), MIN(id) FROM "+brokenDst).Scan(&count, &id); err != nil || count != 1 || id != 3 {
		t.Fatalf("failed copy left count=%d min id=%d err=%v", count, id, err)
	}
	exec(source, "UPDATE "+brokenSrc+" SET enabled='off' WHERE id=2")
	if err := Run(ctx, copyFlags); err != nil {
		t.Fatalf("retry after correcting the source row: %v", err)
	}
	checkRows := func() {
		t.Helper()
		var values string
		err := target.QueryRowContext(ctx, "SELECT string_agg(id::text || '=' || enabled::text, ',' ORDER BY id) FROM "+brokenDst).Scan(&values)
		if err != nil || values != "1=true,2=false,3=false" {
			t.Fatalf("migrated and pre-existing rows = %q, err=%v", values, err)
		}
	}
	checkRows()
	if err := Run(ctx, copyFlags); err == nil {
		t.Fatal("copying the same primary keys twice reported success")
	}
	checkRows()
}
