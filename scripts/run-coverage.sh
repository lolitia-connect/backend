#!/usr/bin/env bash
set -u

raw_profile=coverage-raw.out
profile=coverage.out
generated="$RUNNER_TEMP/ent-generated.txt"
test_status=0
filter_status=0
coverage_status=1


go test -p 1 -count=1 -coverpkg=./... -coverprofile="$raw_profile" ./... || test_status=$?

if [[ -f "$raw_profile" ]]; then
  module=$(go list -m) || filter_status=$?
  if [[ $filter_status -eq 0 ]]; then
    git grep -l -F '// Code generated by ent, DO NOT EDIT.' -- ent/*.go > "$generated" || filter_status=$?
  fi
  if [[ $filter_status -eq 0 ]]; then
    awk -v module="$module" -f scripts/filter-ent-coverage.awk "$generated" "$raw_profile" > "$profile" || filter_status=$?
  fi
fi

if [[ $filter_status -eq 0 && -f "$profile" ]]; then
  GITHUB_TEST_STATUS=$test_status awk -v minimum=80 -f scripts/check-coverage.awk "$profile"
  coverage_status=$?
else
  GITHUB_TEST_STATUS=$test_status GITHUB_COVERAGE_ERROR="coverage profile generation failed (status $filter_status)" \
  awk -v minimum=80 -f scripts/check-coverage.awk /dev/null
  coverage_status=$?
fi

if [[ $test_status -ne 0 ]]; then
  exit "$test_status"
fi
exit "$coverage_status"
