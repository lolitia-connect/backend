#!/usr/bin/env bash
set -u

profile=coverage.out
work_dir=$(mktemp -d "${RUNNER_TEMP:-${TMPDIR:-/tmp}}/backend-coverage.XXXXXXXX") || exit 1
trap 'rm -rf -- "$work_dir"' EXIT
raw_profile="$work_dir/raw.out"
generated="$work_dir/ent-generated.txt"

prepare_coverage() {
  module=$(go list -m) || return
  git grep -l -F '// Code generated by ent, DO NOT EDIT.' -- 'ent/*.go' > "$generated"
  local grep_status=$?
  if [[ $grep_status -gt 1 ]]; then
    return "$grep_status"
  fi
  go list -f '{{.ImportPath}}{{range .GoFiles}} {{.}}{{end}}{{range .CgoFiles}} {{.}}{{end}}' ./... > "$work_dir/packages.txt" || return
  awk -v module="$module" -f scripts/select-coverage-packages.awk "$generated" "$work_dir/packages.txt" > "$work_dir/selected.txt" || return
  cover_packages=$(paste -sd, "$work_dir/selected.txt") || return
  [[ -n "$cover_packages" ]]
}

test_status=0
filter_status=0
coverage_status=1
rm -f -- "$profile" || exit 1

if prepare_coverage; then
  go test -p 1 -count=1 "-coverpkg=$cover_packages" -coverprofile="$raw_profile" ./... || test_status=$?
  if [[ -f "$raw_profile" ]]; then
    awk -v module="$module" -f scripts/filter-ent-coverage.awk "$generated" "$raw_profile" > "$work_dir/filtered.out" &&
      mv -- "$work_dir/filtered.out" "$profile" || filter_status=$?
  else
    filter_status=1
  fi
else
  test_status=1
  filter_status=1
fi

if [[ $filter_status -eq 0 && -f "$profile" ]]; then
  GITHUB_TEST_STATUS=$test_status awk -v minimum=80 -f scripts/check-coverage.awk "$profile"
  coverage_status=$?
else
  GITHUB_TEST_STATUS=$test_status GITHUB_COVERAGE_ERROR="coverage profile generation failed (status $filter_status)" \
  awk -v minimum=80 -f scripts/check-coverage.awk /dev/null
  coverage_status=$?
fi

if [[ $test_status -ne 0 ]]; then
  exit "$test_status"
fi
exit "$coverage_status"
